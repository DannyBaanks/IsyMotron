#!/usr/bin/env node
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const inputPath = path.join(root, 'catalog', 'gus-models.json');
const outputPath = path.join(root, 'src', 'gus', 'catalog.generated.ts');
const javaOutputPath = path.join(root, 'android', 'app', 'src', 'main', 'java', 'io', 'github', 'dannybaanks', 'isymotron', 'GusCatalog.java');
const swiftOutputPath = path.join(root, 'ios', 'App', 'GusLocal', 'Sources', 'GusLocalPlugin', 'GUSCatalog.generated.swift');

export function validateCatalog(value) {
  if (!value || value.schema !== 1 || !Array.isArray(value.models) || value.models.length === 0) {
    throw new Error('GUS catalogue must have schema 1 and a non-empty models array');
  }
  const ids = new Set();
  for (const model of value.models) {
    for (const key of ['id', 'name', 'repository', 'filename', 'revision', 'url', 'sha256', 'licenseName', 'licenseUrl', 'attribution']) {
      if (typeof model[key] !== 'string' || !model[key].trim()) throw new Error(`model ${model.id ?? '<unknown>'} has invalid ${key}`);
    }
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(model.id)) throw new Error(`invalid model id: ${model.id}`);
    if (ids.has(model.id)) throw new Error(`duplicate model id: ${model.id}`);
    ids.add(model.id);
    if (!Number.isSafeInteger(model.byteCount) || model.byteCount <= 0) throw new Error(`invalid byteCount for ${model.id}`);
    if (!/^[a-f0-9]{40}$/.test(model.revision) || /^(main|latest)$/i.test(model.revision)) throw new Error(`mutable or malformed revision for ${model.id}`);
    if (!/^[a-f0-9]{64}$/.test(model.sha256)) throw new Error(`invalid SHA-256 for ${model.id}`);
    const url = new URL(model.url);
    const expectedUrl = `https://huggingface.co/${model.repository}/resolve/${model.revision}/${model.filename}`;
    if (url.protocol !== 'https:' || url.username || url.password || url.search || url.hash || url.href !== expectedUrl || !model.filename.endsWith('.gguf')) {
      throw new Error(`untrusted or non-pinned model URL for ${model.id}`);
    }
    const licenseUrl = new URL(model.licenseUrl);
    if (licenseUrl.protocol !== 'https:' || licenseUrl.username || licenseUrl.password) throw new Error(`invalid license URL for ${model.id}`);
  }
  return value.models;
}

export function generateCatalogSource(value) {
  const models = validateCatalog(value);
  return `// Generated by tools/generate-gus-catalog.mjs from catalog/gus-models.json. Do not edit.\n` +
    `export type GusModelManifest = ${JSON.stringify({
      id: 'string', name: 'string', repository: 'string', filename: 'string', revision: 'string', url: 'string',
      byteCount: 'number', sha256: 'string', licenseName: 'string', licenseUrl: 'string', attribution: 'string',
    }).replaceAll('"', '')};\n\n` +
    `export const GUS_MODELS: readonly GusModelManifest[] = ${JSON.stringify(models, null, 2)} as const;\n\n` +
    `const modelsById = new Map<string, GusModelManifest>(GUS_MODELS.map((model) => [model.id, model]));\n` +
    `export function getGusModel(id: string): GusModelManifest | undefined {\n  return modelsById.get(id);\n}\n`;
}

export function generateJavaCatalogSource(value) {
  const models = validateCatalog(value);
  const literal = (text) => JSON.stringify(text);
  const entries = models.map((model) => `        new Model(${[
    model.id, model.name, model.repository, model.filename, model.revision, model.url,
    String(model.byteCount), model.sha256, model.licenseName, model.licenseUrl, model.attribution,
  ].map((field, index) => index === 6 ? field : literal(field)).join(', ')})`).join(',\n');
  return `// Generated by tools/generate-gus-catalog.mjs from catalog/gus-models.json. Do not edit.\n` +
    `package io.github.dannybaanks.isymotron;\n\n` +
    `import java.util.Arrays;\nimport java.util.Collections;\nimport java.util.List;\n\n` +
    `public final class GusCatalog {\n    private GusCatalog() {}\n\n` +
    `    public static final class Model {\n` +
    `        public final String id, name, repository, filename, revision, url, sha256, licenseName, licenseUrl, attribution;\n` +
    `        public final long byteCount;\n` +
    `        public Model(String id, String name, String repository, String filename, String revision, String url, long byteCount, String sha256, String licenseName, String licenseUrl, String attribution) {\n` +
    `            this.id = id; this.name = name; this.repository = repository; this.filename = filename; this.revision = revision; this.url = url; this.byteCount = byteCount; this.sha256 = sha256; this.licenseName = licenseName; this.licenseUrl = licenseUrl; this.attribution = attribution;\n` +
    `        }\n    }\n\n` +
    `    private static final List<Model> MODELS = Collections.unmodifiableList(Arrays.asList(\n${entries}\n    ));\n` +
    `    public static List<Model> all() { return MODELS; }\n` +
    `    public static Model find(String id) { if (id == null) return null; for (Model model : MODELS) if (model.id.equals(id)) return model; return null; }\n` +
    `}\n`;
}

export function generateSwiftCatalogSource(value) {
  const models = validateCatalog(value);
  const literal = (text) => JSON.stringify(text);
  const entries = models.map((model) => `        GusModelManifest(id: ${literal(model.id)}, name: ${literal(model.name)}, repository: ${literal(model.repository)}, filename: ${literal(model.filename)}, revision: ${literal(model.revision)}, url: URL(string: ${literal(model.url)})!, byteCount: ${model.byteCount}, sha256: ${literal(model.sha256)}, licenseName: ${literal(model.licenseName)}, licenseURL: URL(string: ${literal(model.licenseUrl)})!, attribution: ${literal(model.attribution)})`).join(',\n');
  return `// Generated by tools/generate-gus-catalog.mjs from catalog/gus-models.json. Do not edit.\n` +
    `import Foundation\nimport GusModelStore\n\n` +
    `enum GUSCatalog {\n    static let models: [GusModelManifest] = [\n${entries}\n    ]\n}\n`;
}

const mode = process.argv[2] ?? '--write';
if (!['--write', '--check'].includes(mode)) throw new Error(`unknown option: ${mode}`);
const source = generateCatalogSource(JSON.parse(await readFile(inputPath, 'utf8')));
if (mode === '--check') {
  const current = await readFile(outputPath, 'utf8');
  if (current !== source) throw new Error('catalog.generated.ts is stale; run node tools/generate-gus-catalog.mjs --write');
  const javaSource = generateJavaCatalogSource(JSON.parse(await readFile(inputPath, 'utf8')));
  const javaCurrent = await readFile(javaOutputPath, 'utf8');
  if (javaCurrent !== javaSource) throw new Error('GusCatalog.java is stale; run node tools/generate-gus-catalog.mjs --write');
  const swiftSource = generateSwiftCatalogSource(JSON.parse(await readFile(inputPath, 'utf8')));
  const swiftCurrent = await readFile(swiftOutputPath, 'utf8');
  if (swiftCurrent !== swiftSource) throw new Error('GUSCatalog.generated.swift is stale; run node tools/generate-gus-catalog.mjs --write');
  process.stdout.write('GUS TypeScript, Java, and Swift catalogues verified\n');
} else {
  await writeFile(outputPath, source, 'utf8');
  await writeFile(javaOutputPath, generateJavaCatalogSource(JSON.parse(await readFile(inputPath, 'utf8'))), 'utf8');
  await writeFile(swiftOutputPath, generateSwiftCatalogSource(JSON.parse(await readFile(inputPath, 'utf8'))), 'utf8');
  process.stdout.write('generated TypeScript, Java, and Swift GUS catalogues\n');
}
