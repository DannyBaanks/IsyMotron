#!/usr/bin/env node
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const inputPath = path.join(root, 'catalog', 'gus-models.json');
const outputPath = path.join(root, 'src', 'gus', 'catalog.generated.ts');

export function validateCatalog(value) {
  if (!value || value.schema !== 1 || !Array.isArray(value.models) || value.models.length === 0) {
    throw new Error('GUS catalogue must have schema 1 and a non-empty models array');
  }
  const ids = new Set();
  for (const model of value.models) {
    for (const key of ['id', 'name', 'repository', 'filename', 'revision', 'url', 'sha256', 'licenseName', 'licenseUrl', 'attribution']) {
      if (typeof model[key] !== 'string' || !model[key].trim()) throw new Error(`model ${model.id ?? '<unknown>'} has invalid ${key}`);
    }
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(model.id)) throw new Error(`invalid model id: ${model.id}`);
    if (ids.has(model.id)) throw new Error(`duplicate model id: ${model.id}`);
    ids.add(model.id);
    if (!Number.isSafeInteger(model.byteCount) || model.byteCount <= 0) throw new Error(`invalid byteCount for ${model.id}`);
    if (!/^[a-f0-9]{40}$/.test(model.revision) || /^(main|latest)$/i.test(model.revision)) throw new Error(`mutable or malformed revision for ${model.id}`);
    if (!/^[a-f0-9]{64}$/.test(model.sha256)) throw new Error(`invalid SHA-256 for ${model.id}`);
    const url = new URL(model.url);
    const expectedUrl = `https://huggingface.co/${model.repository}/resolve/${model.revision}/${model.filename}`;
    if (url.protocol !== 'https:' || url.username || url.password || url.search || url.hash || url.href !== expectedUrl || !model.filename.endsWith('.gguf')) {
      throw new Error(`untrusted or non-pinned model URL for ${model.id}`);
    }
    const licenseUrl = new URL(model.licenseUrl);
    if (licenseUrl.protocol !== 'https:' || licenseUrl.username || licenseUrl.password) throw new Error(`invalid license URL for ${model.id}`);
  }
  return value.models;
}

export function generateCatalogSource(value) {
  const models = validateCatalog(value);
  return `// Generated by tools/generate-gus-catalog.mjs from catalog/gus-models.json. Do not edit.\n` +
    `export type GusModelManifest = ${JSON.stringify({
      id: 'string', name: 'string', repository: 'string', filename: 'string', revision: 'string', url: 'string',
      byteCount: 'number', sha256: 'string', licenseName: 'string', licenseUrl: 'string', attribution: 'string',
    }).replaceAll('"', '')};\n\n` +
    `export const GUS_MODELS: readonly GusModelManifest[] = ${JSON.stringify(models, null, 2)} as const;\n\n` +
    `const modelsById = new Map<string, GusModelManifest>(GUS_MODELS.map((model) => [model.id, model]));\n` +
    `export function getGusModel(id: string): GusModelManifest | undefined {\n  return modelsById.get(id);\n}\n`;
}

const mode = process.argv[2] ?? '--write';
if (!['--write', '--check'].includes(mode)) throw new Error(`unknown option: ${mode}`);
const source = generateCatalogSource(JSON.parse(await readFile(inputPath, 'utf8')));
if (mode === '--check') {
  const current = await readFile(outputPath, 'utf8');
  if (current !== source) throw new Error('catalog.generated.ts is stale; run node tools/generate-gus-catalog.mjs --write');
  process.stdout.write('GUS TypeScript catalogue verified\n');
} else {
  await writeFile(outputPath, source, 'utf8');
  process.stdout.write('generated src/gus/catalog.generated.ts\n');
}
